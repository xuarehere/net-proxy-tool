"""Two-file CLI transactions, executed by real POSIX sh in an isolated root tree."""
import os
import json
from pathlib import Path
import shlex
import shutil
import stat
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]


@unittest.skipUnless(os.name != 'nt', 'requires POSIX sh')
class DockerProxyStateTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix='npt-docker-cli-')
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.profile = self.root / 'etc/profile.d/net-proxy.sh'
        self.environment = self.root / 'etc/environment'
        self.state = self.root / 'var/lib/net-proxy-tool/docker-proxy'
        (self.root / 'etc').mkdir()
        self.env = dict(os.environ)
        self.proxy = 'http://selected.invalid:7890'
        self.source = (ROOT / 'bin/docker-proxy-state.sh').read_text()
        # Test-only relocation. The shipped script has fixed container paths.
        for path in ('/etc/profile.d/net-proxy.sh', '/etc/environment', '/var/lib/net-proxy-tool', '/etc/profile.d'):
            self.source = self.source.replace(path, str(self.root) + path)
        # Avoid double prefixing /etc/profile.d during the second replacement.
        self.source = self.source.replace(str(self.root) + str(self.root), str(self.root))

    def run_action(self, action):
        profile = '# Generated by net-proxy-tool\nexport http_proxy=' + shlex.quote(self.proxy)
        environment = 'http_proxy="' + self.proxy + '" # net-proxy-tool'
        script = ('action=' + action + '\nprofile_content=' + shlex.quote(profile) +
                  '\nenvironment_content=' + shlex.quote(environment) + '\n' + self.source)
        return subprocess.run(['sh'], input=script, text=True, capture_output=True, env=self.env, timeout=10)

    def write(self, path, body, mode):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(body)
        path.chmod(mode)

    def snapshot(self):
        return {str(path): (path.read_bytes(), stat.S_IMODE(path.stat().st_mode), path.stat().st_uid,
                           path.stat().st_gid) if path.exists() else None
                for path in (self.profile, self.environment)}

    def seed(self):
        self.write(self.profile, b'# Generated by net-proxy-tool\nexport http_proxy="http://original.invalid:1"\n# custom\n', 0o640)
        self.write(self.environment, b'CUSTOM="kept"\nhttp_proxy="http://fixture:secret@old.invalid:2"\n'
                   b'https_proxy="http://older.invalid:3" # net-proxy-tool\n', 0o600)

    def fail_one_target_copy(self):
        binary = self.root / 'fixture-bin/cp'
        binary.parent.mkdir()
        marker = self.root / 'injected'
        script = ('#!/bin/sh\nfor last; do :; done\nif [ "$last" = ' + shlex.quote(str(self.environment)) +
                  ' ] && [ ! -f ' + shlex.quote(str(marker)) + ' ]; then\n: > ' + shlex.quote(str(marker)) +
                  '; exit 1\nfi\nexec ' + shlex.quote(shutil.which('cp')) + ' "$@"\n')
        binary.write_text(script)
        binary.chmod(0o700)
        self.env['PATH'] = str(binary.parent) + os.pathsep + self.env['PATH']

    def test_absent_files_and_created_directories_are_removed(self):
        before = self.snapshot()
        self.assertEqual(self.run_action('on').returncode, 0)
        self.assertIn(self.proxy.encode(), self.profile.read_bytes())
        self.assertIn(self.proxy.encode(), self.environment.read_bytes())
        self.assertEqual(self.run_action('off').returncode, 0)
        self.assertEqual(self.snapshot(), before)
        self.assertFalse(self.profile.parent.exists())
        self.assertFalse((self.root / 'var').exists())
        self.assertEqual(self.run_action('off').returncode, 0)

    def test_existing_old_proxy_and_repeated_on_restore_first_bytes_and_permissions(self):
        self.seed()
        before = self.snapshot()
        self.assertEqual(self.run_action('on').returncode, 0)
        self.proxy = 'http://second.invalid:7891'
        self.assertEqual(self.run_action('on').returncode, 0)
        self.assertIn(self.proxy.encode(), self.environment.read_bytes())
        self.assertEqual(self.run_action('off').returncode, 0)
        self.assertEqual(self.snapshot(), before)
        cleaned = self.run_action('off')
        self.assertEqual(cleaned.returncode, 0, cleaned.stderr)
        self.assertFalse(self.profile.exists())
        self.assertEqual(self.environment.read_bytes(),
                         b'CUSTOM="kept"\nhttp_proxy="http://fixture:secret@old.invalid:2"\n')  # pragma: allowlist secret
        self.assertNotIn('fixture:secret', cleaned.stderr + cleaned.stdout)

    def test_operator_content_and_permission_changes_refuse_both_actions(self):
        self.seed()
        self.assertEqual(self.run_action('on').returncode, 0)
        self.environment.write_bytes(self.environment.read_bytes() + b'# operator\n')
        edited = self.snapshot()
        for action in ('on', 'off'):
            self.assertNotEqual(self.run_action(action).returncode, 0)
            self.assertEqual(self.snapshot(), edited)

    def test_operator_permission_change_is_also_a_conflict(self):
        self.seed()
        self.assertEqual(self.run_action('on').returncode, 0)
        self.profile.chmod(0o600)
        edited = self.snapshot()
        self.assertNotEqual(self.run_action('off').returncode, 0)
        self.assertEqual(self.snapshot(), edited)

    def test_activation_partial_failure_rolls_back_and_can_retry(self):
        self.seed()
        before = self.snapshot()
        self.fail_one_target_copy()
        self.assertNotEqual(self.run_action('on').returncode, 0)
        self.assertEqual(self.snapshot(), before)
        self.assertFalse((self.state / 'lock').exists())
        self.assertFalse(list(self.state.glob('transaction.*')))
        self.assertEqual(self.run_action('on').returncode, 0)
        self.assertEqual(self.run_action('off').returncode, 0)
        self.assertEqual(self.snapshot(), before)

    def test_restoration_partial_failure_rolls_back_and_can_retry(self):
        self.seed()
        before = self.snapshot()
        self.assertEqual(self.run_action('on').returncode, 0)
        active = self.snapshot()
        self.fail_one_target_copy()
        self.assertNotEqual(self.run_action('off').returncode, 0)
        self.assertEqual(self.snapshot(), active)
        self.assertEqual(self.run_action('off').returncode, 0)
        self.assertEqual(self.snapshot(), before)

    def test_other_application_profile_and_legacy_off_are_untouched(self):
        self.seed()
        self.profile.write_bytes(b'# different application\nexport CUSTOM=kept\n')
        before = self.snapshot()
        for action in ('on', 'off'):
            self.assertNotEqual(self.run_action(action).returncode, 0)
            self.assertEqual(self.snapshot(), before)
        self.assertFalse(self.state.exists())

    def test_legacy_tool_owned_docker_files_without_state_are_cleaned_on_off(self):
        self.write(self.profile, b'# Generated by net-proxy-tool\nexport http_proxy="http://legacy.invalid:7890"\n', 0o644)
        self.write(self.environment, b'CUSTOM="kept"\nHTTP_PROXY="http://legacy.invalid:7890" # net-proxy-tool\n', 0o644)
        result = self.run_action('off')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(self.profile.exists())
        self.assertEqual(self.environment.read_bytes(), b'CUSTOM="kept"\n')

    def test_symlink_refuses_writes_to_either_target(self):
        self.seed()
        self.profile.unlink()
        self.profile.symlink_to(self.environment)
        before = self.environment.read_bytes()
        self.assertNotEqual(self.run_action('on').returncode, 0)
        self.assertEqual(self.environment.read_bytes(), before)

    @unittest.skipUnless(shutil.which('bash'), 'CLI entry point requires Bash')
    def test_cli_on_off_status_and_exec_preserve_their_dispatch(self):
        binary = self.root / 'fixture-bin/docker'
        binary.parent.mkdir()
        binary.write_text('#!' + sys.executable + '\n' + r'''
import os, subprocess, sys
args=sys.argv[1:]
assert args[0]=='exec'
separator=args.index('--')
assert args[separator+1]=='isolated-fixture'
command=args[separator+2:]
root=os.environ['NPT_FIXTURE_ROOT']
def relocate(text):
    for p in ('/etc/profile.d/net-proxy.sh','/etc/environment','/var/lib/net-proxy-tool','/etc/profile.d'):
        text=text.replace(p,root+p)
    return text.replace(root+root,root)
if '-i' in args[:separator]:
    result=subprocess.run(command,input=relocate(sys.stdin.read()),text=True)
else:
    result=subprocess.run([relocate(arg) for arg in command])
sys.exit(result.returncode)
''')
        binary.chmod(0o700)
        (binary.parent / 'python3').symlink_to(sys.executable)
        config = self.root / 'config.json'
        config.write_text(json.dumps({'gateways': [{'id': 'fixture', 'host': 'selected.invalid', 'port': 7890}],
                                     'active_gateway_id': 'fixture'}))
        env = dict(self.env, NET_PROXY_CONFIG=str(config), NPT_FIXTURE_ROOT=str(self.root),
                   PATH=str(binary.parent) + os.pathsep + self.env['PATH'])
        def cli(action, *arguments):
            return subprocess.run(['bash', str(ROOT / 'bin/docker-proxy'), action, 'isolated-fixture', *arguments],
                                  env=env, capture_output=True, text=True, timeout=15)
        self.assertEqual(cli('status').stdout.strip(), 'off')
        result = cli('on')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(cli('status').stdout.strip(), 'on')
        active = self.snapshot()
        result = cli('exec', 'sh', '-c', 'printf "%s" "$HTTP_PROXY"')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, self.proxy)
        self.assertEqual(self.snapshot(), active)
        self.assertEqual(cli('off').returncode, 0)
        self.assertEqual(cli('status').stdout.strip(), 'off')


if __name__ == '__main__':
    unittest.main()
