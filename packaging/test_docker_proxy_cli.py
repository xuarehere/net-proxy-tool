"""Verify the CLI's fixed two-file script in real, offline disposable containers."""
import argparse
import json
from pathlib import Path
import shlex
import subprocess
import uuid

ROOT = Path(__file__).resolve().parents[1]


def main(image):
    prefix = 'npt-cli-' + uuid.uuid4().hex[:12]
    target, sibling = prefix + '-target', prefix + '-sibling'
    source = (ROOT / 'bin/docker-proxy-state.sh').read_text(encoding='utf-8')
    paths = ['/etc/profile.d/net-proxy.sh', '/etc/environment']

    def run(*args, data=None, check=True):
        return subprocess.run(args, input=data, capture_output=True, check=check, timeout=30)

    def snapshot(container):
        code = ('import pathlib,hashlib,json,stat; paths=' + repr(paths) + '; '
                'print(json.dumps({p: [hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest(),'
                'stat.S_IMODE(pathlib.Path(p).stat().st_mode),pathlib.Path(p).stat().st_uid,'
                'pathlib.Path(p).stat().st_gid] if pathlib.Path(p).exists() else None for p in paths},sort_keys=True))')
        return run('docker', 'exec', container, 'python', '-c', code).stdout

    def action(value, proxy='http://selected.invalid:7890'):
        content = '# Generated by net-proxy-tool\nexport http_proxy=' + shlex.quote(proxy)
        environment = 'http_proxy="' + proxy + '" # net-proxy-tool'
        script = ('action=' + value + '\nprofile_content=' + shlex.quote(content) +
                  '\nenvironment_content=' + shlex.quote(environment) + '\n' + source)
        return run('docker', 'exec', '-i', target, 'sh', data=script.encode(), check=False)

    try:
        for name in (target, sibling):
            run('docker', 'run', '--rm', '--network', 'none', '--name', name, '-d', '--entrypoint', 'sleep', image, '300')
        neighbor_before = snapshot(sibling)
        for existing in (False, True):
            records = {paths[0]: '# Generated by net-proxy-tool\nexport http_proxy=http://old.invalid:2\n',
                       paths[1]: 'CUSTOM=kept\nhttp_proxy=http://old.invalid:2 # net-proxy-tool\n'} if existing else {}
            code = ('import pathlib,json; data=json.loads(' + repr(json.dumps(records)) + '); '
                    'paths=' + repr(paths) + '; '
                    '[(pathlib.Path(p).write_text(data[p]),pathlib.Path(p).chmod(0o640)) '
                    'if p in data else pathlib.Path(p).unlink(missing_ok=True) for p in paths]')
            run('docker', 'exec', target, 'python', '-c', code)
            before = snapshot(target)
            for proxy in ('http://selected.invalid:7890', 'http://second.invalid:7891'):
                result = action('on', proxy)
                assert result.returncode == 0, result.stderr.decode()
            result = action('off')
            assert result.returncode == 0, result.stderr.decode()
            assert snapshot(target) == before
            assert snapshot(sibling) == neighbor_before
        result = action('on')
        assert result.returncode == 0, result.stderr.decode()
        run('docker', 'exec', target, 'sh', '-c', "printf '# operator edit\\n' >> /etc/environment")
        edited = snapshot(target)
        for value in ('on', 'off'):
            assert action(value).returncode != 0
            assert snapshot(target) == edited
        assert snapshot(sibling) == neighbor_before
        print('Docker CLI: existing/absent files, repeated activation, exact restoration, edit refusal and sibling isolation passed.')
    finally:
        for name in (target, sibling):
            run('docker', 'rm', '-f', name, check=False)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--node-image', required=True)
    main(parser.parse_args().node_image)
