validate_profile_markers() {
    awk '
        /^# --- NET-PROXY-TOOL-START ---$/ {if (inside) exit 1; inside=1}
        /^# --- NET-PROXY-TOOL-END ---$/ {if (!inside) exit 1; inside=0}
        END {if (inside) exit 1}
    ' "$1"
}

strip_tool_markers() {
    awk -v kind="$1" '
        /^# --- NET-PROXY-TOOL-START ---$/ {inside=1; next}
        /^# --- NET-PROXY-TOOL-END ---$/ {inside=0; next}
        /^# net-proxy-tool:start$/ {npt=1; next}
        /^# net-proxy-tool:end$/ {npt=0; next}
        /^\/\/ net-proxy-tool:start$/ {npt=1; next}
        /^\/\/ net-proxy-tool:end$/ {npt=0; next}
        inside || npt {next}
        $0 == "[ -r \"$HOME/.net-proxy-switch.sh\" ] && . \"$HOME/.net-proxy-switch.sh\"" {next}
        $0 == "[ -r /etc/profile.d/net-proxy.sh ] && . /etc/profile.d/net-proxy.sh" {next}
        $0 == "[ -r /etc/profile.d/net-proxy-switch.sh ] && . /etc/profile.d/net-proxy-switch.sh" {next}
        / # net-proxy-tool$/ || /^# net-proxy-tool$/ {next}
        (kind == "etc-profile-d" || kind == "apt") && (/^# Generated by net-proxy-tool$/ || /^\/\/ Generated by net-proxy-tool$/) {next}
        {print}
    ' "$2"
}

file_has_tool_markers() {
    [ -f "$1" ] || return 1
    grep -qsF 'NET-PROXY-TOOL-START' "$1" 2>/dev/null ||
        grep -qsF '.net-proxy-switch.sh' "$1" 2>/dev/null ||
        grep -qsF 'net-proxy-tool' "$1" 2>/dev/null
}

clean_file_in_place() {
    cf_kind=$1 cf_file=$2
    [ -f "$cf_file" ] && [ ! -L "$cf_file" ] || return 0
    file_has_tool_markers "$cf_file" || return 0
    if [ "$cf_kind" = profile ] || [ "$cf_kind" = etc-profile ]; then
        validate_profile_markers "$cf_file" || {
            echo "Incomplete legacy proxy block: $cf_file. No managed files were changed; review the markers first." >&2
            exit 1
        }
    fi
    cf_tmp=$(mktemp)
    cp -p "$cf_file" "$cf_tmp"
    strip_tool_markers "$cf_kind" "$cf_file" > "$cf_tmp.clean"
    if [ "$cf_kind" = etc-profile-d ] || [ "$cf_kind" = apt ]; then
        if ! grep -q '[^[:space:]]' "$cf_tmp.clean" 2>/dev/null; then
            rm -f "$cf_file" "$cf_tmp" "$cf_tmp.clean"
            return 0
        fi
    fi
    cat "$cf_tmp.clean" > "$cf_tmp"
    rm -f "$cf_tmp.clean"
    cp -p "$cf_tmp" "$cf_file"
    rm -f "$cf_tmp"
}

cleanup_legacy_user_and_system() {
    if [ -f "$HOME/.net-proxy-switch.sh" ] && [ ! -L "$HOME/.net-proxy-switch.sh" ]; then
        rm -f "$HOME/.net-proxy-switch.sh"
    fi
    for lf in "$HOME/.bashrc" "$HOME/.bash_profile" "$HOME/.profile" "$HOME/.bash_login" "${ZDOTDIR:-$HOME}/.zprofile"; do
        clean_file_in_place profile "$lf"
    done
    cf_curl="$HOME/.curlrc"
    if [ -n "${CURL_HOME-}" ] && [ -r "$CURL_HOME/.curlrc" ]; then cf_curl="$CURL_HOME/.curlrc"
    elif [ -n "${XDG_CONFIG_HOME-}" ] && [ -r "$XDG_CONFIG_HOME/curlrc" ]; then cf_curl="$XDG_CONFIG_HOME/curlrc"; fi
    for lf in "$HOME/.curlrc" "$cf_curl" "$HOME/.wgetrc" "$HOME/.config/pip/pip.conf"; do
        clean_file_in_place config "$lf"
    done
    etc_dirty=false
    for ef in /etc/profile.d/net-proxy.sh /etc/profile.d/net-proxy-switch.sh /etc/environment /etc/bash.bashrc /etc/profile /etc/curlrc /etc/wgetrc /etc/pip.conf /etc/apt/apt.conf.d/99net-proxy; do
        if file_has_tool_markers "$ef"; then etc_dirty=true; break; fi
    done
    if [ "$etc_dirty" = true ]; then
        if [ "$(id -u)" = 0 ]; then
            for ef in /etc/profile.d/net-proxy.sh /etc/profile.d/net-proxy-switch.sh; do
                if [ -f "$ef" ] && grep -qsF '# Generated by net-proxy-tool' "$ef" 2>/dev/null; then rm -f "$ef"; fi
            done
            for ef in /etc/bash.bashrc /etc/profile; do clean_file_in_place etc-profile "$ef"; done
            for ef in /etc/environment /etc/curlrc /etc/wgetrc /etc/pip.conf; do clean_file_in_place config "$ef"; done
            clean_file_in_place apt /etc/apt/apt.conf.d/99net-proxy
        elif command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then
            sudo -n sh -s <<'NPT_SYS_CLEAN'
set -eu
for ef in /etc/profile.d/net-proxy.sh /etc/profile.d/net-proxy-switch.sh; do
    if [ -f "$ef" ] && grep -qsF '# Generated by net-proxy-tool' "$ef" 2>/dev/null; then rm -f "$ef"; fi
done
for ef in /etc/bash.bashrc /etc/profile /etc/environment /etc/curlrc /etc/wgetrc /etc/pip.conf /etc/apt/apt.conf.d/99net-proxy; do
    [ -f "$ef" ] && [ ! -L "$ef" ] || continue
    grep -qsE 'NET-PROXY-TOOL-START|net-proxy-tool' "$ef" 2>/dev/null || continue
    tmp=$(mktemp)
    cp -p "$ef" "$tmp"
    awk '
        /^# --- NET-PROXY-TOOL-START ---$/ {inside=1; next}
        /^# --- NET-PROXY-TOOL-END ---$/ {inside=0; next}
        /^# net-proxy-tool:start$/ {npt=1; next}
        /^# net-proxy-tool:end$/ {npt=0; next}
        /^\/\/ net-proxy-tool:start$/ {npt=1; next}
        /^\/\/ net-proxy-tool:end$/ {npt=0; next}
        inside || npt {next}
        / # net-proxy-tool$/ || /^# net-proxy-tool$/ || /^# Generated by net-proxy-tool$/ || /^\/\/ Generated by net-proxy-tool$/ {next}
        {print}
    ' "$ef" > "$tmp.clean"
    if [ "$ef" = /etc/apt/apt.conf.d/99net-proxy ] && ! grep -q '[^[:space:]]' "$tmp.clean" 2>/dev/null; then
        rm -f "$ef" "$tmp" "$tmp.clean"
        continue
    fi
    cat "$tmp.clean" > "$tmp"
    rm -f "$tmp.clean"
    cp -p "$tmp" "$ef"
    rm -f "$tmp"
done
NPT_SYS_CLEAN
        else
            echo 'Cannot remove system-wide net-proxy-tool configuration in /etc without elevated privileges.' >&2
            exit 1
        fi
    fi
}

