case "$curl_file" in /*) ;; *) curl_file="$(pwd)/$curl_file" ;; esac
if [ -f "$state/curl-active/path" ]; then
    saved_curl_file=$(cat "$state/curl-active/path")
    if [ "$action" = on ] && [ "$saved_curl_file" != "$curl_file" ]; then
        echo "Curl configuration context changed. Restore the previous activation before switching again." >&2
        exit 1
    fi
    curl_file="$saved_curl_file"
fi

# Each snapshot belongs to one exact path. Never restore over an operator edit.
manage() {
    key=$1 file=$2 kind=$3
    dir="$state/$key"
    if [ -L "$dir" ]; then echo 'Refusing a symbolic link in a file snapshot.' >&2; exit 1; fi
    if [ -d "$dir" ] && [ ! -w "$dir" ]; then echo 'Snapshot directory is not writable; no target was changed.' >&2; exit 1; fi
    for item in original applied absent next restore path; do
        if [ -L "$dir/$item" ]; then echo 'Refusing a symbolic link in a file snapshot.' >&2; exit 1; fi
    done
    case "$file" in *'
'*) echo 'Newlines in managed paths are unsupported.' >&2; exit 1 ;; esac
    if [ "$action" = off ] && [ ! -d "$dir" ]; then return; fi
    if [ -f "$dir/path" ] && [ "$(cat "$dir/path")" != "$file" ]; then
        echo "Snapshot path changed: $file. Restore using the original context." >&2; exit 1
    fi
    if [ -L "$file" ] || { [ -e "$file" ] && [ ! -f "$file" ]; }; then
        echo "Refusing to replace non-regular file: $file" >&2; exit 1
    fi
    if [ -f "$dir/original" ] && [ -f "$dir/absent" ]; then
        echo "Conflicting snapshot records: $dir. Review them before restoring." >&2; exit 1
    fi
    if [ "$stage" != commit ] && [ -e "$dir/applied" ]; then
        if [ ! -f "$dir/original" ] && [ ! -f "$dir/absent" ]; then
            echo "Missing restoration baseline: $dir. No overwrite is authorized." >&2; exit 1
        fi
        if ! same_file "$file" "$dir/applied" && ! { [ -f "$dir/next" ] && same_file "$file" "$dir/next"; }; then
            echo "Edited since activation: $file. Original snapshot: $dir" >&2; exit 1
        fi
    elif [ "$stage" != commit ] && [ ! -f "$transaction/prepared.$key" ] && { { [ -f "$dir/original" ] && ! same_file "$file" "$dir/original"; } ||
         { [ -f "$dir/absent" ] && [ -e "$file" ]; }; }; then
        # A failed preparation can leave snapshots without applied files. Do not
        # mistake a subsequent operator edit for something that we may overwrite.
        stripped_matches=false
        if [ "$action" = off ] && file_has_tool_markers "$file"; then
            if [ -f "$dir/original" ] && [ "$(metadata "$file")" = "$(metadata "$dir/original")" ]; then
                strip_tool_markers "$kind" "$file" > "$transaction/stripped.$key"
                if cmp -s "$transaction/stripped.$key" "$dir/original"; then stripped_matches=true; fi
                rm -f "$transaction/stripped.$key"
            elif [ -f "$dir/absent" ] && { [ "$kind" = env ] || [ "$kind" = etc-profile-d ] || [ "$kind" = apt ]; }; then
                stripped_matches=true
            fi
        fi
        if [ "$stripped_matches" != true ] && ! { [ -f "$dir/next" ] && same_file "$file" "$dir/next"; }; then
            echo "Edited since snapshot preparation: $file. Original snapshot: $dir" >&2; exit 1
        fi
    fi
    if [ "$stage" = check ] && [ "$action" = on ] && [ "$kind" = profile ] && [ -f "$file" ]; then
        # Only complete, exact legacy blocks can be replaced in the applied copy.
        # Reject unmatched/nested markers before any managed file is written.
        if ! awk '
            /^# --- NET-PROXY-TOOL-START ---$/ {if (inside) exit 1; inside=1}
            /^# --- NET-PROXY-TOOL-END ---$/ {if (!inside) exit 1; inside=0}
            END {if (inside) exit 1}
            ' "$file"; then
            echo "Incomplete legacy proxy block: $file. No managed files were changed; review the markers first." >&2
            exit 1
        fi
    fi
    if [ "$stage" = check ]; then return; fi
    if [ "$stage" = apply ]; then
        printf '%s\n' "$file" > "$transaction/file-$key.path"
        if [ -f "$file" ]; then cp -p "$file" "$transaction/file-$key.before"; fi
        printf '%s\n' "$key" >> "$transaction/journal"
    fi
    if [ "$action" = off ]; then
        # An interrupted snapshot with neither baseline record cannot authorize deletion.
        if [ ! -f "$dir/original" ] && [ ! -f "$dir/absent" ]; then return; fi
        if [ "$stage" = prepare ]; then
            if [ -f "$dir/original" ]; then cp -p "$dir/original" "$dir/restore"; fi
            : > "$transaction/prepared.$key"
            return
        fi
        if [ "$stage" = apply ]; then
            if [ -f "$dir/original" ]; then cp -p "$dir/restore" "$file"; else rm -f "$file"; fi
            return
        fi
        rm -f "$dir/original" "$dir/applied" "$dir/absent" "$dir/next" "$dir/restore" "$dir/pip.tmp" "$dir/path"
        if [ -f "$state/.activation/previous-$key-path.original" ]; then
            cp -p "$state/.activation/previous-$key-path.original" "$dir/path"
        fi
        if [ ! -f "$state/.activation/created-snapshots" ] || grep -qxF "$key" "$state/.activation/created-snapshots"; then rmdir "$dir" 2>/dev/null || :; fi
        return
    fi
    if [ "$stage" = commit ]; then mv "$dir/next" "$dir/applied"; return; fi
    if [ "$stage" = apply ]; then
        ensure_parent "$(dirname "$file")"
        cp -p "$dir/next" "$file"
        return
    fi
    if [ ! -d "$dir" ] && [ -f "$state/.activation/created-snapshots" ]; then printf '%s\n' "$key" >> "$state/.activation/created-snapshots"; fi
    mkdir -p "$dir"
    printf '%s\n' "$file" > "$dir/path"
    printf '%s\n' "$uid" > "$state/owner-uid"
    if [ -n "$npt_owner" ]; then printf '%s\n' "$npt_owner" > "$state/owner-node-id"; fi
    if [ ! -f "$state/snapshot-id" ]; then od -An -N16 -tx1 /dev/urandom | tr -d ' \n' > "$state/snapshot-id"; fi
    if [ ! -e "$dir/original" ] && [ ! -e "$dir/absent" ]; then
        if [ "$kind" = env ]; then
            : > "$dir/absent"
        elif [ "$kind" = etc-profile-d ]; then
            if [ -f "$file" ]; then
                strip_tool_markers etc-profile-d "$file" > "$dir/original.clean"
                if grep -q '[^[:space:]]' "$dir/original.clean" 2>/dev/null; then
                    cp -p "$file" "$dir/original"
                    cat "$dir/original.clean" > "$dir/original"
                else
                    : > "$dir/absent"
                fi
                rm -f "$dir/original.clean"
            else
                : > "$dir/absent"
            fi
        elif [ -f "$file" ]; then
            cp -p "$file" "$dir/original"
            if file_has_tool_markers "$file"; then
                strip_tool_markers "$kind" "$file" > "$dir/original.clean"
                cat "$dir/original.clean" > "$dir/original"
                rm -f "$dir/original.clean"
            fi
        else
            : > "$dir/absent"
        fi
    fi
    next="$dir/next"
    if [ -f "$dir/original" ]; then cp -p "$dir/original" "$next"; else : > "$next"; fi
    case "$kind" in
        curl) printf '\n# net-proxy-tool:start\nproxy = "%s"\nnoproxy = "%s"\n# net-proxy-tool:end\n' "$proxy" "$bypass" >> "$next" ;;
        wget) printf '\n# net-proxy-tool:start\nhttp_proxy = %s\nhttps_proxy = %s\n# net-proxy-tool:end\n' "$proxy" "$proxy" >> "$next" ;;
        apt) printf '\n// net-proxy-tool:start\nAcquire::http::Proxy "%s";\nAcquire::https::Proxy "%s";\n// net-proxy-tool:end\n' "$proxy" "$proxy" >> "$next" ;;
        git) git config --file "$next" --replace-all http.proxy "$proxy"
             git config --file "$next" --replace-all https.proxy "$proxy" ;;
        pip) awk -v proxy="$proxy" '
             /^[[:space:]]*\[/ {
                 section=tolower($0)
                 global=(section ~ /^[[:space:]]*\[global\][[:space:]]*$/)
                 if (global) { print; print "# net-proxy-tool:start"; print "proxy = " proxy; print "# net-proxy-tool:end"; found=1; next }
             }
             global && /^[[:space:]]*[Pp][Rr][Oo][Xx][Yy][[:space:]]*[:=]/ {next}
             {print}
             END {if (!found) print "\n[global]\n# net-proxy-tool:start\nproxy = " proxy "\n# net-proxy-tool:end"}
             ' "$next" > "$dir/pip.tmp"
             cat "$dir/pip.tmp" > "$next"; rm -f "$dir/pip.tmp" ;;
        env) printf '# Generated by net-proxy-tool\nexport HTTP_PROXY="%s" HTTPS_PROXY="%s" http_proxy="%s" https_proxy="%s"\nexport NO_PROXY="%s" no_proxy="%s"\n' "$proxy" "$proxy" "$proxy" "$proxy" "$bypass" "$bypass" > "$next" ;;
        etc-profile-d) printf '# Generated by net-proxy-tool\nexport HTTP_PROXY="%s" HTTPS_PROXY="%s" http_proxy="%s" https_proxy="%s"\nexport NO_PROXY="%s" no_proxy="%s"\n' "$proxy" "$proxy" "$proxy" "$proxy" "$bypass" "$bypass" > "$next" ;;
        etc-env) printf '\n# net-proxy-tool:start\nHTTP_PROXY="%s"\nHTTPS_PROXY="%s"\nhttp_proxy="%s"\nhttps_proxy="%s"\nNO_PROXY="%s"\nno_proxy="%s"\n# net-proxy-tool:end\n' "$proxy" "$proxy" "$proxy" "$proxy" "$bypass" "$bypass" >> "$next" ;;
        profile) { printf '%s\n' '[ -r "$HOME/.net-proxy-switch.sh" ] && . "$HOME/.net-proxy-switch.sh"'
                   if [ -f "$dir/original" ]; then
                       strip_tool_markers profile "$dir/original"
                   fi
                   printf '\n%s\n' '[ -r "$HOME/.net-proxy-switch.sh" ] && . "$HOME/.net-proxy-switch.sh"'
                 } > "$next" ;;
    esac
    : > "$transaction/prepared.$key"
}

# Every next file must be generated successfully before the first target write.
for stage in check prepare apply commit; do
    manage curlrc "$HOME/.curlrc" curl
    if [ "$curl_file" != "$HOME/.curlrc" ]; then manage curl-active "$curl_file" curl; fi
    manage wgetrc "$HOME/.wgetrc" wget
    manage pip "$HOME/.config/pip/pip.conf" pip
    if command -v git >/dev/null 2>&1 || [ "$action" = off ]; then manage git "$HOME/.gitconfig" git; fi
    manage env "$HOME/.net-proxy-switch.sh" env
    for name in .bashrc .profile .bash_profile .bash_login; do
        if [ "$name" = .profile ] || [ -f "$HOME/$name" ] || [ -d "$state/$name" ]; then manage "$name" "$HOME/$name" profile; fi
    done
    if [ "$action" = off ] && [ -f "$state/zprofile/path" ]; then manage zprofile "$(cat "$state/zprofile/path")" profile
    else case "${NPT_BASELINE_SHELL-}" in */zsh) manage zprofile "${ZDOTDIR:-$HOME}/.zprofile" profile ;; esac; fi
    if [ "$(id -u)" = 0 ]; then
        # Standard curl does not read /etc/curlrc. Only restore/update an old managed snapshot.
        if [ -d "$state/system-curl" ]; then manage system-curl /etc/curlrc curl; fi
        manage system-pip /etc/pip.conf pip
        if command -v git >/dev/null 2>&1 || [ "$action" = off ]; then manage system-git /etc/gitconfig git; fi
        if [ -d /etc/apt/apt.conf.d ]; then manage apt /etc/apt/apt.conf.d/99net-proxy apt; fi
        if [ "$npt_is_docker" = 1 ]; then
            if [ -d /etc/profile.d ] || [ -d "$state/etc-profile-d" ] || [ "$action" = on ]; then
                manage etc-profile-d /etc/profile.d/net-proxy.sh etc-profile-d
            fi
            manage etc-env /etc/environment etc-env
            manage system-wget /etc/wgetrc wget
        fi
    fi
done
if [ "$action" = off ]; then
    cleanup_legacy_user_and_system
fi
rm -f "$transaction/journal"
if [ "$action" = off ] && [ -d "$state/.activation" ]; then
    cleanup_dirs=$(awk 'NF {paths[++n]=$0} END {for(i=1;i<=n;i++) print paths[i]}' "$state/.activation/created-dirs")
    for name in owner-uid owner-node-id snapshot-id; do
        if [ -f "$state/.activation/$name.original" ]; then cp -p "$state/.activation/$name.original" "$state/$name"
        elif [ -f "$state/.activation/$name.absent" ]; then rm -f "$state/$name"; fi
    done
    for file in "$state/.activation"/*; do [ ! -f "$file" ] || rm -f "$file"; done
    rmdir "$state/.activation"
fi
