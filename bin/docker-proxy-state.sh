# Fixed operation streamed by docker-proxy into the selected container.
# action/profile_content/environment_content are shell-quoted by the controller.
set -eu
umask 077
profile=/etc/profile.d/net-proxy.sh
environment=/etc/environment
state=/var/lib/net-proxy-tool/docker-proxy
case "$action" in on|off) ;; *) exit 2 ;; esac

metadata() { stat -c '%a:%u:%g' "$1" 2>/dev/null || stat -f '%Lp:%u:%g' "$1"; }
same() { cmp -s "$1" "$2" && [ "$(metadata "$1")" = "$(metadata "$2")" ]; }
fail() { printf '%s\n' "$1" >&2; exit 1; }
target() { case "$1" in profile) printf '%s\n' "$profile" ;; environment) printf '%s\n' "$environment" ;; esac; }

for path in /var/lib/net-proxy-tool /etc/profile.d "$state" "$profile" "$environment"; do
    [ ! -L "$path" ] || fail 'Refusing a symbolic link in managed paths.'
done
if [ "$action" = off ] && [ ! -d "$state" ]; then
    if grep -qx '# Generated by net-proxy-tool' "$profile" 2>/dev/null ||
       grep -q ' # net-proxy-tool$' "$environment" 2>/dev/null; then
        fail 'Legacy proxy settings have no restoration snapshot. Explicitly enable once to preserve this baseline; nothing was removed.'
    fi
    exit 0
fi
if [ "$action" = on ] && [ -f "$profile" ] && [ ! -f "$state/profile/applied" ] &&
   ! grep -qx '# Generated by net-proxy-tool' "$profile"; then
    fail 'Existing profile belongs to another application; nothing was changed.'
fi

new_dirs=''
if [ ! -d "$state" ]; then
    path=$state
    while [ ! -e "$path" ]; do new_dirs="$new_dirs
$path"; path=$(dirname "$path"); done
    mkdir -p "$state"
    printf '1\n' > "$state/version"
    printf '%s\n' "$new_dirs" > "$state/created-dirs"
elif [ ! -f "$state/version" ] || [ "$(cat "$state/version")" != 1 ]; then
    fail 'Unknown snapshot directory; nothing was changed.'
fi
owner=$(metadata "$state"); owner=${owner#*:}; owner=${owner%%:*}
[ "$owner" = "$(id -u)" ] || fail 'Snapshot belongs to a different execution account.'
mkdir "$state/lock" || fail 'Another container proxy operation is in progress.'
transaction=$(mktemp -d "$state/transaction.XXXXXX")
mutation=false
cleanup_state=false
finish() {
    code=$?
    set +e
    trap - EXIT HUP INT TERM
    if [ "$code" -ne 0 ] && [ "$mutation" = true ]; then
        for key in profile environment; do
            file=$(target "$key")
            if [ -f "$transaction/$key.before" ]; then cp -p "$transaction/$key.before" "$file"
            elif [ -f "$transaction/$key.absent" ]; then rm -f "$file"; fi
            mkdir -p "$state/$key"
            for record in original absent applied next; do
                if [ -f "$transaction/$key.$record.before" ]; then cp -p "$transaction/$key.$record.before" "$state/$key/$record"
                elif [ -f "$transaction/$key.$record.absent" ]; then rm -f "$state/$key/$record"; fi
            done
        done
        for name in version created-dirs; do
            [ ! -f "$transaction/$name.before" ] || cp -p "$transaction/$name.before" "$state/$name"
        done
        if [ -f "$transaction/created-dirs" ]; then
            while IFS= read -r path; do rmdir "$path" 2>/dev/null || :; done < "$transaction/created-dirs"
        fi
    fi
    for temporary in "$transaction"/*; do [ ! -f "$temporary" ] || rm -f "$temporary"; done
    rmdir "$transaction" 2>/dev/null || :
    rmdir "$state/lock" 2>/dev/null || :
    if [ "$code" -eq 0 ] && [ "$cleanup_state" = true ]; then
        printf '%s\n' "$cleanup_dirs" | while IFS= read -r path; do [ -z "$path" ] || rmdir "$path" 2>/dev/null || :; done
    fi
    exit "$code"
}
trap finish EXIT
trap 'exit 130' HUP INT TERM

# Check both paths and all prior snapshots before preparing or writing either.
for key in profile environment; do
    file=$(target "$key")
    dir="$state/$key"
    [ ! -e "$file" ] || [ -f "$file" ] || fail 'A managed target is not a regular file.'
    [ ! -L "$dir" ] || fail 'A snapshot directory is a symbolic link.'
    [ ! -d "$dir" ] || [ -w "$dir" ] || fail 'Snapshot directory is not writable.'
    for record in original absent applied next; do
        [ ! -L "$dir/$record" ] || fail 'Snapshot records must be regular files.'
    done
    if [ -f "$dir/original" ] && [ -f "$dir/absent" ]; then fail 'Conflicting restoration records.'; fi
    if [ -f "$dir/applied" ]; then
        { [ -f "$dir/original" ] || [ -f "$dir/absent" ]; } || fail 'Missing restoration baseline.'
        same "$file" "$dir/applied" || { [ -f "$dir/next" ] && same "$file" "$dir/next"; } || fail 'Edited since activation; nothing was overwritten.'
    elif [ -f "$dir/original" ]; then
        same "$file" "$dir/original" || { [ -f "$dir/next" ] && same "$file" "$dir/next"; } || fail 'Edited since snapshot preparation; nothing was overwritten.'
    elif [ -f "$dir/absent" ] && [ -e "$file" ]; then
        { [ -f "$dir/next" ] && same "$file" "$dir/next"; } || fail 'Created since snapshot preparation; nothing was overwritten.'
    fi
done

# Prepare both outputs, including their original modes, before target writes.
for key in profile environment; do
    file=$(target "$key")
    dir="$state/$key"
    if [ "$action" = on ]; then
        mkdir -p "$dir"
        if [ ! -f "$dir/original" ] && [ ! -f "$dir/absent" ]; then
            if [ -f "$file" ]; then cp -p "$file" "$dir/original"; else : > "$dir/absent"; fi
        fi
        if [ -f "$dir/original" ]; then cp -p "$dir/original" "$dir/next"
        else : > "$dir/next"; chmod 644 "$dir/next"; fi
        if [ "$key" = profile ]; then printf '%s\n' "$profile_content" > "$dir/next"
        else
            if [ -f "$dir/original" ]; then sed '/ # net-proxy-tool$/d' "$dir/original" > "$transaction/environment.content"
            else : > "$transaction/environment.content"; fi
            printf '\n%s\n' "$environment_content" >> "$transaction/environment.content"
            cat "$transaction/environment.content" > "$dir/next"
        fi
    elif [ -f "$dir/original" ]; then cp -p "$dir/original" "$dir/restore"; fi
done

# Rollback covers both target writes and snapshot bookkeeping, so a retry can
# always compare against the last committed activation or untouched baseline.
for key in profile environment; do
    file=$(target "$key")
    dir="$state/$key"
    if [ -f "$file" ]; then cp -p "$file" "$transaction/$key.before"; else : > "$transaction/$key.absent"; fi
    for record in original absent applied next; do
        if [ -f "$dir/$record" ]; then cp -p "$dir/$record" "$transaction/$key.$record.before"
        else : > "$transaction/$key.$record.absent"; fi
    done
done
for name in version created-dirs; do cp -p "$state/$name" "$transaction/$name.before"; done
mutation=true
for key in profile environment; do
    file=$(target "$key")
    dir="$state/$key"
    if [ "$action" = on ]; then
        parent=$(dirname "$file")
        if [ ! -d "$parent" ]; then
            mkdir -p "$parent"; chmod 755 "$parent"
            printf '%s\n' "$parent" >> "$state/created-dirs"
            printf '%s\n' "$parent" >> "$transaction/created-dirs"
        fi
        cp -p "$dir/next" "$file"
    elif [ -f "$dir/original" ]; then cp -p "$dir/restore" "$file"
    elif [ -f "$dir/absent" ]; then rm -f "$file"; fi
done
if [ "$action" = on ]; then
    for key in profile environment; do mv "$state/$key/next" "$state/$key/applied"; done
else
    for key in profile environment; do
        for record in original absent applied next restore; do rm -f "$state/$key/$record"; done
        rmdir "$state/$key" 2>/dev/null || :
    done
    cleanup_dirs=$(cat "$state/created-dirs")
    rm -f "$state/version" "$state/created-dirs"
    cleanup_state=true
fi
